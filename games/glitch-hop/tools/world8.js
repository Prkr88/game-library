const fs = require('fs');
class L {
  constructor(W, H, name, par) { this.W = W; this.H = H; this.name = name; this.par = par; this.g = Array.from({ length: H }, () => Array(W).fill('.')); }
  put(c, n, ch) { this.g[this.H - 1 - n][c] = ch; return this; }
  G(c0, c1, n = 3) { for (let c = c0; c <= c1; c++) for (let k = 0; k < n; k++) this.put(c, k, '#'); return this; }
  B(c0, c1, n0, n1, ch = '#') { for (let c = c0; c <= c1; c++) for (let k = n0; k <= n1; k++) this.put(c, k, ch); return this; }
  rows() { return this.g.map(r => r.join('')); }
}
const out = [];
let l, chainw;
const pit = (l, c0, c1) => { l.G(c0, c1, 1); l.B(c0, c1, 0, 0, '^'); };

// island sequence: [gap, width, height n, char, saw|null, coin?]; ground-level pit below
const run = (l, specs, a0 = 8) => { let a = a0, pn = 3; specs.forEach(([gap, w, n, ch, saw, coin]) => { ch = ch === 'a' ? 'x' : ch === 'b' ? '#' : ch; a += gap; n = Math.min(n, pn + 1); if (ch === 'x') n = Math.min(n, pn); pn = n; w = ch === 'i' ? Math.max(w, 4) : ch === 'x' ? w : Math.max(w, 3); l.B(a, a + w - 1, n, n, ch); if (saw && w >= 3 && !'abx'.includes(ch)) l.put(a + (w >> 1), n + 3, saw); if (coin) l.put(a + (w >> 1), n + 2, 'o'); a += w; }); return a; };
const fin = (l, a) => { l.G(a + 2, l.W - 1, 3); l.put(a + 5, 3, 'E'); };
