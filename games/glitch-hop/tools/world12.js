// builds src/levels12.js (world 12: Dash Remix). Run: node tools/world12.js
const fs = require('fs');
class L {
  constructor(W, H, name, par) { this.W = W; this.H = H; this.name = name; this.par = par; this.g = Array.from({ length: H }, () => Array(W).fill('.')); }
  put(c, n, ch) { this.g[this.H - 1 - n][c] = ch; return this; }
  G(c0, c1, n = 3) { for (let c = c0; c <= c1; c++) for (let k = 0; k < n; k++) this.put(c, k, '#'); return this; }
  B(c0, c1, n0, n1, ch = '#') { for (let c = c0; c <= c1; c++) for (let k = n0; k <= n1; k++) this.put(c, k, ch); return this; }
  rows() { return this.g.map(r => r.join('')); }
}
const out = [];
let l;
const pit = (l, c0, c1) => { l.G(c0, c1, 1); l.B(c0, c1, 0, 0, '^'); };
// chain: [gap, ferry ('M'|'N'), next island width, next island height n, char, saw, coin, ferry row nf]
// island tops at row n; ferry placed mid-gap at row nf (platform top = top of that row)
const chain = (l, segs, a0 = 8, n0 = 3) => {
  let a = a0, pn = n0;
  segs.forEach(([gap, f, w, n, ch, saw, coin, nf]) => {
    ch = ch || '#';
    const mid = a + (gap >> 1);
    l.put(mid, nf === undefined ? Math.max(pn, n) : nf, f);
    a += gap;
    l.B(a, a + w - 1, n, n, ch);
    if (saw) l.put(a + (w >> 1), n + 3, saw);
    if (coin) l.put(a + (w >> 1), n + 2, 'o');
    a += w; pn = n;
  });
  return a;
};
const fin = (l, a, n = 3) => { l.G(a + 2, l.W - 1, n); l.put(a + 5, n, 'E'); };
// wind helper: column of wind char over gap midpoint-ish, rows n0..n1
const wind = (l, c, n0, n1, ch) => l.B(c, c, n0, n1, ch);

// dash islands: [gap, width, height n, char, saw, coin]
const dchain = (l, segs, a0 = 8, n0 = 3) => {
  let a = a0;
  segs.forEach(([gap, w, n, ch, saw, coin, ceil]) => {
    ch = ch || '#';
    a += gap;
    l.B(a, a + w - 1, n, n, ch);
    if (saw) l.put(a - (gap >> 1), n + 3, saw);
    if (coin) l.put(a + (w >> 1), n + 2, 'o');
    if (ceil) l.put(a - (gap >> 1), n + 6, '~');
    a += w;
  });
  return a;
};
// 61 Dash Ferry: wide 7-8 gaps
l = new L(110, 16, 'Dash Gaps', 41);
l.G(0, 7).G(102, 109); pit(l, 8, 101);
fin(l, dchain(l, [[7, 3, 3, '#', 'W'], [8, 3, 3, '#', 'w', 1], [7, 3, 4, 'i', 'W'], [8, 3, 3, '#', 'w'], [8, 3, 3, 'x', 'W'], [8, 3, 3, '#', 'w']]));
l.put(1, 3, 'S');
out.push(l);
// 62 Dash Rain: ceiling spikes + saws, ice and crumble landings
l = new L(120, 20, 'Dash Rain', 30);
l.G(0, 7).G(112, 119); pit(l, 8, 111);
fin(l, dchain(l, [[7, 3, 4, 'i', 'W', 0, 1], [7, 3, 5, 'x', 'w', 0, 1], [8, 3, 4, 'i', 'W', 1, 1], [7, 3, 3, 'x', 'w', 0, 1], [8, 3, 4, '#', 'W', 0, 1], [7, 3, 3, 'i', 'w', 0, 1]]));
l.put(1, 3, 'S');
out.push(l);
// 63 Dash Belts: belts against run direction
l = new L(130, 18, 'Dash Belts', 28);
l.G(0, 7).G(122, 129); pit(l, 8, 121);
fin(l, dchain(l, [[7, 4, 3, '<', 'W'], [7, 4, 3, '>', 'w'], [7, 4, 4, '>', 'W', 1], [7, 4, 3, 'i', 'w'], [7, 4, 3, '<', 'W'], [7, 4, 3, 'x', 'w'], [7, 4, 3, '>', 'W']]));
l.put(1, 3, 'S');
out.push(l);
// 64 Dash Stairs: tall climbs and drops, narrow landings
l = new L(130, 22, 'Dash Stairs', 14);
l.G(0, 7).G(122, 129); pit(l, 8, 121);
fin(l, dchain(l, [[6, 3, 4, '#', 'W', 0, 1], [6, 3, 5, 'i', 'w', 0, 1], [6, 3, 4, '#', 'W', 0, 1], [6, 3, 6, 'x', 'w', 1, 1], [7, 3, 4, 'i', 'W', 0, 1], [7, 3, 3, '#', 'w', 0, 1]]));
l.put(1, 3, 'S');
out.push(l);
// 65 Dash Finale: long gauntlet
l = new L(200, 22, 'Dash Finale', 48);
l.G(0, 7).G(192, 199); pit(l, 8, 191);
fin(l, dchain(l, [[7, 3, 3, 'i', 'W'], [7, 3, 4, 'x', 'w', 0, 1], [7, 4, 3, '<', 'W', 1], [7, 3, 3, 'i', 'w'], [7, 3, 5, '#', 'W', 0, 1], [7, 3, 4, 'x', 'w'], [7, 4, 3, '>', 'W', 1], [7, 3, 4, 'i', 'w', 0, 1], [7, 3, 3, 'x', 'W'], [7, 3, 4, 'i', 'w', 1], [7, 3, 3, '#', 'W', 0, 1], [8, 3, 3, 'i', 'w'], [7, 4, 3, '<', 'W'], [8, 3, 3, 'i', 'w']]));
l.put(1, 3, 'S');
