l.B(37, 39, 1, 9, 'u').B(40, 45, 8, 8, '#');
l.B(47, 49, 1, 7, 'u').B(50, 55, 6, 6, '#').B(57, 59, 1, 5, 'u').B(60, 66, 4, 4, '#');
l.put(1, 3, 'S').put(76, 3, 'E');
[[13, 8], [22, 9], [42, 10], [53, 8]].forEach(([c, n]) => l.put(c, n, 'o'));
out.push(l);
// 37 Thermals: tight ceiling spikes above updrafts
l = new L(90, 15, 'Thermals', 18);
l.G(0, 6).G(82, 89); pit(l, 7, 81);
k = 0;
for (let c = 9; c < 78; c += 11, k++) {
  const top = 5 + (k % 3) * 2;
  l.B(c - 1, c + 1, 1, top + 1, 'u').B(c + 2, c + 6, top, top, '#');
  for (let q = c - 1; q <= c + 1; q++) l.put(q, top + 3, '~');
}
l.put(1, 3, 'S').put(86, 3, 'E');
[[16, 8], [38, 10], [60, 9]].forEach(([c, n]) => l.put(c, n, 'o'));
out.push(l);
// 38 Downdraft: v columns push you down onto spikes if you jump late
l = new L(96, 14, 'Downdraft', 19);
l.G(0, 6).G(88, 95); pit(l, 7, 87);
[4, 5, 6, 5, 6, 5, 4].forEach((n, k) => { const a = 9 + 9 * k; l.B(a, a + 6, n, n, '#'); if (k < 6) l.B(a + 7, a + 8, n + 2, 11, 'v'); });
l.B(72, 84, 4, 4, '#');
l.put(1, 3, 'S').put(92, 3, 'E');
[[21, 8], [39, 8], [57, 8]].forEach(([c, n]) => l.put(c, n, 'o'));
out.push(l);
// chain: updraft column then platform, repeated (stride 11). spec: [T (column top), platform char, saw char|null, ceiling spikes?, downdraft above platform?]
const chain = (l, specs, a0 = 9) => specs.forEach(([T, ch, saw, ceil, dd], k) => {
  const a = a0 + 11 * k;
  l.B(a - 1, a + 1, 1, T, 'u');
  l.B(a + 2, a + 8, T - 1, T - 1, ch);
  if (saw) l.put(a + 5, T + 2, saw);
  if (ceil) l.B(a - 1, a + 1, T + 3, T + 3, '~');
  if (dd) l.B(a + 6, a + 7, T + 2, T + 5, 'v');
});
// 39 Gale Mix: wind + ice + belts + saws
l = new L(90, 17, 'Gale Mix', 17);
l.G(0, 6).G(77, 89); pit(l, 7, 76);
chain(l, [[7, '#', 'W', 0, 0], [9, 'i', null, 0, 0], [8, '>', 'W', 1, 0], [10, '#', null, 0, 1], [8, 'i', 'w', 1, 0], [9, '>', null, 0, 1]]);
