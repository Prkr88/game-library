// builds src/levels11.js (world 10: Overdrive, hard all-mechanic mixes). Run: node tools/world10.js
const fs = require('fs');
class L {
  constructor(W, H, name, par) { this.W = W; this.H = H; this.name = name; this.par = par; this.g = Array.from({ length: H }, () => Array(W).fill('.')); }
  put(c, n, ch) { this.g[this.H - 1 - n][c] = ch; return this; }
  G(c0, c1, n = 3) { for (let c = c0; c <= c1; c++) for (let k = 0; k < n; k++) this.put(c, k, '#'); return this; }
  B(c0, c1, n0, n1, ch = '#') { for (let c = c0; c <= c1; c++) for (let k = n0; k <= n1; k++) this.put(c, k, ch); return this; }
  rows() { return this.g.map(r => r.join('')); }
}
const out = [];
let l;
const pit = (l, c0, c1) => { l.G(c0, c1, 1); l.B(c0, c1, 0, 0, '^'); };
// chain: [gap, ferry ('M'|'N'), next island width, next island height n, char, saw, coin, ferry row nf]
// island tops at row n; ferry placed mid-gap at row nf (platform top = top of that row)
const chain = (l, segs, a0 = 8, n0 = 3) => {
  let a = a0, pn = n0;
  segs.forEach(([gap, f, w, n, ch, saw, coin, nf]) => {
    ch = ch || '#';
    const mid = a + (gap >> 1);
    l.put(mid, nf === undefined ? Math.max(pn, n) : nf, f);
    a += gap;
    l.B(a, a + w - 1, n, n, ch);
    if (saw) l.put(a + (w >> 1), n + 3, saw);
    if (coin) l.put(a + (w >> 1), n + 2, 'o');
    a += w; pn = n;
  });
  return a;
};
const fin = (l, a, n = 3) => { l.G(a + 2, l.W - 1, n); l.put(a + 5, n, 'E'); };
// wind helper: column of wind char over gap midpoint-ish, rows n0..n1
const wind = (l, c, n0, n1, ch) => l.B(c, c, n0, n1, ch);

// dash islands: [gap, width, height n, char, saw, coin]
const dchain = (l, segs, a0 = 8, n0 = 3) => {
  let a = a0;
  segs.forEach(([gap, w, n, ch, saw, coin, ceil]) => {
    ch = ch || '#';
    a += gap;
    l.B(a, a + w - 1, n, n, ch);
    if (saw) l.put(a - (gap >> 1), n + 3, saw);
    if (coin) l.put(a + (w >> 1), n + 2, 'o');
    if (ceil) l.put(a - (gap >> 1), n + 6, '~');
    a += w;
  });
  return a;
};
// 56 Dash Intro
l = new L(90, 14, 'Dash Intro', 11);
l.G(0, 7).G(82, 89); pit(l, 8, 81);
fin(l, dchain(l, [[6, 4, 3], [6, 4, 3], [7, 3, 3, '#', 0, 1], [7, 3, 4], [7, 4, 3]]));
l.put(1, 3, 'S');
out.push(l);
// 57 Dash Sawmill: wide gaps, saws mid-gap
l = new L(110, 16, 'Dash Sawmill', 13);
l.G(0, 7).G(102, 109); pit(l, 8, 101);
fin(l, dchain(l, [[6, 3, 3, '#', 'W'], [7, 3, 3, '#', 'w'], [7, 3, 4, '#', 'W', 1], [7, 3, 3, 'x', 'w'], [7, 3, 3, '#', 'W'], [7, 3, 3, '#', 'w']]));
l.put(1, 3, 'S');
out.push(l);
// 58 Dash Ice: wide gaps onto ice
l = new L(110, 16, 'Dash Ice', 14);
l.G(0, 7).G(102, 109); pit(l, 8, 101);
fin(l, dchain(l, [[6, 4, 3, 'i'], [7, 3, 3, 'i', 'W'], [7, 4, 4, 'i', 'w', 1], [7, 3, 3, 'i'], [7, 4, 3, 'i', 'W'], [7, 3, 3, 'i', 'w']]));
l.put(1, 3, 'S');
out.push(l);
// 59 Dash Climb: ascending with ceiling spikes
l = new L(110, 20, 'Dash Climb', 12);
l.G(0, 7).G(102, 109); pit(l, 8, 101);
fin(l, dchain(l, [[6, 3, 4, '#', 0, 0, 1], [6, 3, 5, '#', 'W', 0, 1], [6, 3, 6, '#', 0, 1, 1], [6, 3, 5, 'x', 'w', 0, 1], [7, 3, 4, '#', 'W', 0, 1], [7, 3, 3, '#', 0, 0, 1]]));
l.put(1, 3, 'S');
out.push(l);
// 60 Dash Core: finale
l = new L(160, 20, 'Dash Core', 38);
l.G(0, 7).G(152, 159); pit(l, 8, 151);
fin(l, dchain(l, [[6, 3, 3, 'i', 'W'], [7, 3, 4, 'x', 'w'], [7, 3, 3, '#', 'W', 1], [7, 3, 3, 'i', 'w'], [7, 3, 5, '#', 'W', 0, 1], [7, 3, 3, '<', 'w'], [7, 3, 4, 'i', 'W', 1], [7, 3, 3, 'x', 'w'], [7, 3, 3, '#', 'W', 0, 1], [7, 3, 3, 'i', 'w'], [7, 3, 3, '>', 'W'], [8, 3, 3, 'i', 'w']]));
l.put(1, 3, 'S');
out.push(l);
const data = out.map(l => ({ name: l.name, par: l.par, dash: true, rows: l.rows() }));
