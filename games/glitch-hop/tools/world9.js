// builds src/levels9.js (world 9: Elevators, one-way moving platforms M horizontal / N vertical). Run: node tools/world9.js
const fs = require('fs');
class L {
  constructor(W, H, name, par) { this.W = W; this.H = H; this.name = name; this.par = par; this.g = Array.from({ length: H }, () => Array(W).fill('.')); }
  put(c, n, ch) { this.g[this.H - 1 - n][c] = ch; return this; }
  G(c0, c1, n = 3) { for (let c = c0; c <= c1; c++) for (let k = 0; k < n; k++) this.put(c, k, '#'); return this; }
  B(c0, c1, n0, n1, ch = '#') { for (let c = c0; c <= c1; c++) for (let k = n0; k <= n1; k++) this.put(c, k, ch); return this; }
  rows() { return this.g.map(r => r.join('')); }
}
const out = [];
let l;
const pit = (l, c0, c1) => { l.G(c0, c1, 1); l.B(c0, c1, 0, 0, '^'); };
// chain: [gap, ferry ('M'|'N'), next island width, next island height n, char, saw, coin, ferry row nf]
// island tops at row n; ferry placed mid-gap at row nf (platform top = top of that row)
const chain = (l, segs, a0 = 8, n0 = 3) => {
  let a = a0, pn = n0;
  segs.forEach(([gap, f, w, n, ch, saw, coin, nf]) => {
    ch = ch || '#';
    const mid = a + (gap >> 1);
    l.put(mid, nf === undefined ? Math.max(pn, n) : nf, f);
    a += gap;
    l.B(a, a + w - 1, n, n, ch);
    if (saw) l.put(a + (w >> 1), n + 3, saw);
    if (coin) l.put(a + (w >> 1), n + 2, 'o');
    a += w; pn = n;
  });
  return a;
};
const fin = (l, a, n = 3) => { l.G(a + 2, l.W - 1, n); l.put(a + 5, n, 'E'); };
// 46 Ferry: horizontal ferries across spike pits
l = new L(80, 14, 'Ferry', 19);
l.G(0, 7).G(72, 79); pit(l, 8, 71);
fin(l, chain(l, [[8, 'M', 4, 3], [9, 'M', 3, 3, '#', null, 1], [9, 'M', 4, 3, '#', 'W']]));
l.put(1, 3, 'S');
out.push(l);
// 47 Lift Shaft: vertical elevators between rising ledges
l = new L(80, 26, 'Lift Shaft', 16);
l.G(0, 7); pit(l, 8, 71);
fin(l, chain(l, [[5, 'N', 3, 5, '#', 'W', 0, 4], [5, 'N', 3, 8, '#', 'w', 0, 7], [5, 'N', 3, 11, '#', 'W', 1, 10], [5, 'N', 3, 8, 'i', 'w', 0, 9], [5, 'N', 3, 11, '#', 'W', 0, 10], [5, 'N', 3, 14, '#', 'w', 1, 13]]), 15);
l.put(1, 3, 'S');
out.push(l);
// 48 Saw Ferry: ferries under patrolling saws
l = new L(100, 14, 'Saw Ferry', 30);
l.G(0, 7).G(92, 99); pit(l, 8, 91);
fin(l, chain(l, [[8, 'M', 3, 3, '#', 'W'], [9, 'M', 3, 4, '#', 'w', 1], [8, 'M', 3, 3, 'i', 'W'], [9, 'M', 3, 4, 'x'], [9, 'M', 3, 3, '#', 'w']]));
l.put(1, 3, 'S');
out.push(l);
// 49 Rail Mix: ferries and lifts with crumble and phase islands
l = new L(110, 20, 'Rail Mix', 32);
l.G(0, 7).G(102, 109); pit(l, 8, 101);
fin(l, chain(l, [[8, 'M', 3, 3, 'a', 'W'], [5, 'N', 3, 6, 'b', null, 1, 5], [4, 'M', 3, 6, 'x', 'w'], [5, 'N', 3, 3, '#', 'W', 0, 5], [9, 'M', 3, 3, 'a'], [5, 'N', 3, 6, 'b', 'w', 0, 5], [8, 'M', 3, 6, '>', 'W']]), 6);
l.put(1, 3, 'S');
out.push(l);
// 50 Skyway: long finale
l = new L(150, 22, 'Skyway', 42);
l.G(0, 7); pit(l, 8, 141);
fin(l, chain(l, [[8, 'M', 3, 3, '#', 'W', 1], [5, 'N', 3, 7, '#', 'w', 0, 5], [9, 'M', 3, 7, 'a', 'W'], [5, 'N', 3, 4, 'b', null, 1, 5], [9, 'M', 3, 4, 'i', 'w'], [5, 'N', 3, 8, '>', 'W', 0, 6], [9, 'M', 3, 8, 'i', 'w'], [5, 'N', 3, 4, 'a', 'W', 0, 6], [9, 'M', 3, 4, 'b', 'w', 1], [9, 'M', 3, 3, '#', 'W']]), 3);
l.put(1, 3, 'S');
out.push(l);
const data = out.map(l => ({ name: l.name, par: l.par, rows: l.rows() }));
fs.writeFileSync(__dirname + '/../src/levels9.js', '/* world 9 (elevators), generated by tools/world9.js */\n(function(r){var L=' + JSON.stringify(data, null, 0).replace(/\},\{/g, '},\n{') + ';if(typeof module!==\'undefined\')module.exports=L;else r.GH_LEVELS9=L})(this);\n');
