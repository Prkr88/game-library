// builds src/levels9.js (world 10: Overdrive, hard all-mechanic mixes). Run: node tools/world10.js
const fs = require('fs');
class L {
  constructor(W, H, name, par) { this.W = W; this.H = H; this.name = name; this.par = par; this.g = Array.from({ length: H }, () => Array(W).fill('.')); }
  put(c, n, ch) { this.g[this.H - 1 - n][c] = ch; return this; }
  G(c0, c1, n = 3) { for (let c = c0; c <= c1; c++) for (let k = 0; k < n; k++) this.put(c, k, '#'); return this; }
  B(c0, c1, n0, n1, ch = '#') { for (let c = c0; c <= c1; c++) for (let k = n0; k <= n1; k++) this.put(c, k, ch); return this; }
  rows() { return this.g.map(r => r.join('')); }
}
const out = [];
let l;
const pit = (l, c0, c1) => { l.G(c0, c1, 1); l.B(c0, c1, 0, 0, '^'); };
// chain: [gap, ferry ('M'|'N'), next island width, next island height n, char, saw, coin, ferry row nf]
// island tops at row n; ferry placed mid-gap at row nf (platform top = top of that row)
const chain = (l, segs, a0 = 8, n0 = 3) => {
  let a = a0, pn = n0;
  segs.forEach(([gap, f, w, n, ch, saw, coin, nf]) => {
    ch = ch || '#';
    const mid = a + (gap >> 1);
    l.put(mid, nf === undefined ? Math.max(pn, n) : nf, f);
    a += gap;
    l.B(a, a + w - 1, n, n, ch);
    if (saw) l.put(a + (w >> 1), n + 3, saw);
    if (coin) l.put(a + (w >> 1), n + 2, 'o');
    a += w; pn = n;
  });
  return a;
};
const fin = (l, a, n = 3) => { l.G(a + 2, l.W - 1, n); l.put(a + 5, n, 'E'); };
// wind helper: column of wind char over gap midpoint-ish, rows n0..n1
const wind = (l, c, n0, n1, ch) => l.B(c, c, n0, n1, ch);
// 51 Overdrive Gate: fast ferries + ice landings + saws
l = new L(110, 14, 'Overdrive Gate', 34);
l.G(0, 7).G(102, 109); pit(l, 8, 101);
fin(l, chain(l, [[8, 'M', 3, 3, 'i', 'W'], [9, 'M', 3, 3, 'i', 'w'], [8, 'M', 3, 4, 'x', 'W', 1], [9, 'M', 3, 3, 'i', 'w'], [9, 'M', 3, 3, '#', 'W'], [9, 'M', 3, 3, 'i']]));
l.put(1, 3, 'S');
out.push(l);
// 52 Lift Relay: lifts and ferries over ice/phase/belt islands
l = new L(110, 26, 'Lift Relay', 21);
l.G(0, 7); pit(l, 8, 101);
{
  const e = chain(l, [[5, 'N', 3, 6, 'i', 'W', 0, 5], [5, 'N', 3, 9, '#', 'w', 0, 8], [6, 'M', 3, 9, 'a', 'W'], [5, 'N', 3, 12, 'b', 'w', 1, 11], [6, 'M', 3, 12, 'i', 'W'], [5, 'N', 3, 9, '>', 'w', 0, 10]]);
  
  fin(l, e, 10);
}
l.put(1, 3, 'S');
out.push(l);
// 53 Belt Ferry: belts on every landing against ferry direction
l = new L(120, 16, 'Belt Ferry', 40);
l.G(0, 7).G(112, 119); pit(l, 8, 111);
fin(l, chain(l, [[8, 'M', 3, 3, '>', 'W'], [9, 'M', 3, 4, '<', 'w', 1], [8, 'M', 3, 3, '>', 'W'], [9, 'M', 3, 5, 'a', 'w'], [9, 'M', 3, 3, 'b', 'W'], [9, 'M', 3, 3, 'i', 'w'], [9, 'M', 3, 3, '<']]));
l.put(1, 3, 'S');
out.push(l);
// 54 Crumble Ferry: ferries and lifts between crumble/phase islands
l = new L(120, 20, 'Crumble Ferry', 32);
l.G(0, 7); pit(l, 8, 111);
{
  const e = chain(l, [[8, 'M', 3, 3, '#', 'W'], [5, 'N', 3, 6, 'x', 'w', 0, 5], [8, 'M', 3, 6, 'i', 'W'], [5, 'N', 3, 3, 'a', 'w', 0, 5], [9, 'M', 3, 3, 'b', 'W', 1], [9, 'M', 3, 3, 'x', 'w'], [9, 'M', 3, 3, '>']]);
  
  fin(l, e);
}
l.put(1, 3, 'S');
out.push(l);
// 55 Overdrive Core: finale
l = new L(170, 24, 'Overdrive Core', 51);
l.G(0, 7); pit(l, 8, 161);
fin(l, chain(l, [[8, 'M', 3, 3, 'i', 'W', 1], [5, 'N', 3, 7, 'a', 'w', 0, 5], [9, 'M', 3, 7, 'b', 'W'], [5, 'N', 3, 4, '<', 'w', 0, 6], [9, 'M', 3, 4, 'i', 'W'], [5, 'N', 3, 8, 'x', 'w', 1, 6], [9, 'M', 3, 8, 'a', 'W'], [5, 'N', 3, 4, 'b', 'w', 0, 6], [9, 'M', 3, 4, '>', 'W'], [9, 'M', 3, 3, 'i', 'w', 1], [9, 'M', 3, 3, 'a', 'W'], [9, 'M', 3, 3, 'b', 'w']]), 3);
l.put(1, 3, 'S');
out.push(l);
const data = out.map(l => ({ name: l.name, par: l.par, rows: l.rows() }));
fs.writeFileSync(__dirname + '/../src/levels10.js', '/* world 10 (overdrive), generated by tools/world9.js */\n(function(r){var L=' + JSON.stringify(data, null, 0).replace(/\},\{/g, '},\n{') + ';if(typeof module!==\'undefined\')module.exports=L;else r.GH_LEVELS10=L})(this);\n');
