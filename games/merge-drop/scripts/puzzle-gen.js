// Generates solver-verified puzzles -> src/puzzles.js. Run: node scripts/puzzle-gen.js
const L = require('../src/logic.js');
const fs = require('fs');
const PACK6 = process.argv[2] === 'pack6';
const PACK5 = process.argv[2] === 'pack5' || PACK6;
const PACK4 = process.argv[2] === 'pack4' || PACK5;
const PACK3 = process.argv[2] === 'pack3' || PACK4;
const PACK2 = process.argv[2] === 'pack2' || PACK3;
let seed = PACK6 ? 314159 : PACK5 ? 556677 : PACK4 ? 918273 : PACK3 ? 424242 : PACK2 ? 777777 : 12345;
const rnd = () => { seed ^= seed << 13; seed >>>= 0; seed ^= seed >>> 17; seed ^= seed << 5; seed >>>= 0; return seed / 4294967296; };
const ri = n => Math.floor(rnd() * n);
const enc = v => v === -1 ? 'S' : v === 0 ? '.' : Math.log2(v).toString(36);
function randBoard(fill, stones) {
  const g = []; for (let r = 0; r < 7; r++) g.push([0, 0, 0, 0, 0]);
  const pool = [2, 2, 4, 4, 8, 8, 16, 32];
  for (let t = 0; t < fill; t++) {
    const c = ri(5); let r = 6; while (r >= 0 && g[r][c]) r--;
    if (r < 3) continue;
    for (let k = 0; k < 10; k++) {
      const v = stones && rnd() < 0.12 ? -1 : pool[ri(pool.length)];
      g[r][c] = v;
      if (!L.findGroup(g)) break; g[r][c] = 0;
    }
  }
  return g;
}
function solve(pz, D) { // best[k] = max tile reachable in <=k drops; counts[k][T]
  const best = new Array(D + 1).fill(0); const hits = [];
  function rec(s, k, path) {
    if (s.max > best[k]) best[k] = s.max;
    hits.push({ k, max: s.max, path });
    if (k === D) return;
    for (let c = 0; c < 5; c++) {
      const t = L.snapshot(s), g = s.grid.map(r => r.slice());
      const res = L.drop(s, c);
      if (res) { if (!s.over) rec(s, k + 1, path + c); }
      s.grid = g; L.restore(s, t);
    }
  }
  rec(L.createPuzzle(pz), 0, '');
  for (let k = 1; k <= D; k++) best[k] = Math.max(best[k], best[k - 1]);
  return { best, hits };
}
const levels = PACK2 ? require('../src/puzzles.js').slice(0, PACK6 ? 30 : PACK5 ? 28 : PACK4 ? 24 : PACK3 ? 20 : 12) : [];
const spec = PACK6 ? [[10, 4, 2], [10, 3, 2]] : PACK5 ? [[9, 4, 2], [9, 3, 3]] : PACK4 ? [[9, 3, 2], [9, 3, 1], [9, 2, 1], [9, 4, 1]] : PACK3 ? [[9, 2, 2], [9, 2, 1], [9, 3, 2], [9, 3, 1]] : PACK2 ? [ // pack 2: expert, deeper, tighter limits
  [7, 1, 3], [7, 2, 2], [8, 1, 4], [8, 2, 3], [8, 2, 2], [8, 2, 1],
  [8, 3, 2], [8, 3, 1]] : [ // [par depth, stones, max solutions at par]
  [2, 0, 99], [3, 0, 40], [3, 0, 12], [4, 0, 30], [4, 1, 10], [5, 0, 25], [5, 1, 8],
  [6, 0, 20], [6, 1, 6], [6, 1, 3], [7, 1, 8], [7, 1, 3]];
for (let i = 0; i < spec.length; i++) {
  const [D, stones, maxSol] = spec[i]; let found = null, tries = 0;
  while (!found && tries++ < 400) {
    const g = randBoard(8 + ri(7) + i % 3, stones);
    const bm = Math.max(...g.flat());
    const queue = []; for (let k = 0; k < D + 2; k++) queue.push([2, 2, 4, 4, 8][ri(5)]);
    const pz = { board: g.map(r => r.map(enc).join('')), queue };
    const { best, hits } = solve(pz, D);
    const T = best[D];
    if (T < bm * 2 || T < 16 || best[D - 1] >= T) continue;
    const sols = hits.filter(h => h.k === D && h.max >= T).length;
    if (sols > maxSol || sols < 1) continue;
    found = Object.assign(pz, { goal: T, par: D, limit: D + (PACK2 ? (i < 3 && !PACK3 ? 1 : 0) : i < 6 ? 2 : 1), solutions: sols });
  }
  if (!found) { console.error('fail level', i + 1); process.exit(1); }
  levels.push(found); console.error('level', i + 1, 'par', found.par, 'goal', found.goal, 'solutions', found.solutions, 'tries', tries);
}
fs.writeFileSync(__dirname + '/../src/puzzles.js', '// Generated by scripts/puzzle-gen.js (solver-verified). board rows top->bottom; chars: . empty, S stone, else base36 exponent (1=2,2=4,3=8,...).\n(function (root) {\n  var PUZZLES = ' + JSON.stringify(levels, null, 1).replace(/\n\s+/g, ' ') + ';\n  if (typeof module !== \'undefined\') module.exports = PUZZLES; else root.MergePuzzles = PUZZLES;\n})(this);\n');
