// Adds a "sol" (column string, one optimal par-length line reaching the goal) to every puzzle in src/puzzles.js. Run: node scripts/puzzle-solutions.js
const L = require('../src/logic.js');
const fs = require('fs');
const P = require('../src/puzzles.js');
function find(pz) {
  function rec(s, k, path) {
    if (s.max >= pz.goal) return path;
    if (k === pz.par) return null;
    for (let c = 0; c < 5; c++) {
      const t = L.snapshot(s), g = s.grid.map(r => r.slice());
      const res = L.drop(s, c);
      let r = null;
      if (res && !s.over) r = rec(s, k + 1, path + c);
      s.grid = g; L.restore(s, t);
      if (r) return r;
    }
    return null;
  }
  return rec(L.createPuzzle(pz), 0, '');
}
P.forEach((pz, i) => { pz.sol = find(pz); if (!pz.sol) { console.error('no sol', i + 1); process.exit(1); } console.error('puzzle', i + 1, pz.sol); });
fs.writeFileSync(__dirname + '/../src/puzzles.js', '// Generated by scripts/puzzle-gen.js (solver-verified), "sol" added by scripts/puzzle-solutions.js. board rows top->bottom; chars: . empty, S stone, else base36 exponent (1=2,2=4,3=8,...).\n(function (root) {\n  var PUZZLES = ' + JSON.stringify(P, null, 1).replace(/\n\s+/g, ' ') + ';\n  if (typeof module !== \'undefined\') module.exports = PUZZLES; else root.MergePuzzles = PUZZLES;\n})(this);\n');
